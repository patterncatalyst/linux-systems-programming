// Command gen is the self-contained generator behind
// `//go:generate go run ./internal/gen` (see main.go). It has no external
// dependencies -- stdlib only -- and is invoked from the module root, so the
// working directory when it runs is the go/ module root itself: it writes
// tools_generated.go as a sibling of the //go:generate directive.
//
// Deterministic on purpose: the tool table below is keyed by name and
// deliberately listed out of order in source, but gen sorts the keys before
// rendering and passes the emitted source through go/format. Re-running the
// generator against unchanged input always reproduces the exact same bytes
// -- the property verify.lua's gate B (copy-aside, regenerate, diff) checks.
package main

import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

// toolTable is the hand-maintained source of truth for `toolbox tools`.
// Keys are listed out of alphabetical order on purpose, to prove the
// generator -- not the author -- is what sorts them into generatedTools.
var toolTable = map[string]string{
	"staticcheck":   "advanced static analysis and unused-code detection",
	"gofmt":         "format Go source files",
	"go vet":        "report suspicious constructs the compiler allows",
	"delve":         "the Go debugger (dlv)",
	"go generate":   "run source-code generators referenced by directive",
	"gofumpt":       "a stricter superset of gofmt",
	"golangci-lint": "run many linters through one driver",
	"pprof":         "profile CPU, heap, and goroutine activity",
	"benchstat":     "compare statistical summaries of benchmark runs",
	"govulncheck":   "cross-reference dependencies against the Go vuln DB",
}

const header = "// Code generated by internal/gen. DO NOT EDIT.\n\n"

func render() ([]byte, error) {
	names := make([]string, 0, len(toolTable))
	for name := range toolTable {
		names = append(names, name)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package main\n\n")
	b.WriteString("// Tool describes one entry in the toolbox's tool table.\n")
	b.WriteString("type Tool struct {\n")
	b.WriteString("\tName string\n")
	b.WriteString("\tRole string\n")
	b.WriteString("}\n\n")
	b.WriteString("// generatedTools is sorted by Name; see internal/gen/main.go.\n")
	b.WriteString("var generatedTools = []Tool{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t{Name: %q, Role: %q},\n", name, toolTable[name])
	}
	b.WriteString("}\n")

	return format.Source([]byte(b.String()))
}

func main() {
	out, err := render()
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen: format.Source:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("tools_generated.go", out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen: write tools_generated.go:", err)
		os.Exit(1)
	}
	fmt.Fprintln(os.Stderr, "gen: wrote tools_generated.go")
}
